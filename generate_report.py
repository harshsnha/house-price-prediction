"""Builds the project report (.docx and .html) from model/metrics.json and report_images/.

Usage: python generate_report.py --name "Your Name" --college "Your College"
"""
import argparse
import json
import os
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt

BASE = os.path.dirname(os.path.abspath(__file__))
IMG = os.path.join(BASE, "report_images")

ap = argparse.ArgumentParser()
ap.add_argument("--name", default="Your Name")
ap.add_argument("--college", default="Your College Name")
ap.add_argument("--out", default=None, help="output .docx path")
args = ap.parse_args()

with open(os.path.join(BASE, "model", "metrics.json")) as f:
    m = json.load(f)

best = next(r for r in m["results"] if r["model"] == m["best_model"])
top_feats = list(m["importance"].items())[:3]
top_text = ", ".join(k for k, _ in top_feats)

sections = [
    ("1. Introduction",
     "Buying or selling a house is one of the biggest financial decisions most people make, and the price depends on "
     "many factors at once. This project uses data analytics and machine learning to estimate the price of a house "
     "from its basic details such as city, area, number of rooms, age and location quality. The final model is "
     "wrapped in a small web application so anyone can try it without writing code."),
    ("2. Objectives",
     "To clean and explore a housing dataset, find which factors affect price the most, train and compare several "
     "regression models, pick the best one, and deploy it as a simple web app with a Flask backend."),
    ("3. Dataset",
     f"The dataset has {m['rows']} records with the columns city, area_sqft, bedrooms, bathrooms, age_years, "
     "location_score, parking and price (target). It is generated by data/generate_data.py with realistic price "
     "patterns and a few deliberately missing values, so the same code also works on a real dataset with the "
     f"same columns. The data was split into {m['train_rows']} training rows and {m['test_rows']} test rows."),
    ("4. Tools and technologies",
     "Python, Pandas and NumPy for data handling, Matplotlib for charts, Scikit-learn for modelling, Joblib for "
     "saving the model, Flask for the backend, HTML/CSS/JavaScript for the frontend, and Jupyter Notebook for "
     "the analysis. AI-assisted coding tools were used to speed up development and debugging."),
    ("5. Methodology",
     "Data cleaning: duplicate rows were dropped, missing numeric values were filled with the median and missing "
     "city values with the most common city. Exploration: price distribution, average price by city and a "
     "correlation heatmap were studied. Preprocessing: numeric columns were standardised and the city column "
     "was one-hot encoded inside a single Scikit-learn pipeline, so the same steps run during prediction. "
     "Modelling: Linear Regression, Ridge, Lasso, Random Forest and Gradient Boosting were trained and compared "
     "using R2, MAE, RMSE and 5-fold cross-validation."),
]

charts_eda = [
    ("price_distribution.png", "Figure 1: Price distribution"),
    ("price_by_city.png", "Figure 2: Average price by city"),
    ("correlation_heatmap.png", "Figure 3: Correlation heatmap"),
]
charts_model = [
    ("model_comparison.png", "Figure 4: Model comparison (R2 on test data)"),
    ("actual_vs_predicted.png", "Figure 5: Actual vs predicted price"),
    ("residuals.png", "Figure 6: Residual distribution"),
    ("feature_importance.png", "Figure 7: Feature importance"),
]

results_text = (
    f"{m['best_model']} gave the best cross-validated score and was selected as the final model. On the unseen "
    f"test set it reached an R2 of {best['r2']}, a mean absolute error of about Rs {best['mae']:,} and an RMSE of "
    f"about Rs {best['rmse']:,}. The most influential features were {top_text}."
)
conclusion = (
    "The project shows the full workflow of a small analytics problem: cleaning, exploring, modelling, comparing "
    "and deploying. The model predicts prices well on this dataset. Because the data is synthetic, the scores "
    "will be lower on real market data, where more factors such as locality, builder and market trends matter."
)
future = ("Use a real-world dataset, add more features such as locality and furnishing, tune hyperparameters "
          "with GridSearchCV, and deploy the app on a cloud platform.")

# ---------- docx ----------
doc = Document()
st = doc.styles["Normal"]
st.font.name = "Calibri"
st.font.size = Pt(11)

for _ in range(5):
    doc.add_paragraph()
t = doc.add_paragraph()
t.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = t.add_run("House Price Prediction using Data Analytics with AI")
r.bold = True
r.font.size = Pt(26)
for line in ["Project Report", "", f"Submitted by: {args.name}", args.college,
             "IBM SkillsBuild Data Analytics with AI Internship 2026", "AICTE | BharatCares"]:
    p = doc.add_paragraph(line)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
doc.add_page_break()


def add_figures(items):
    for fname, cap in items:
        path = os.path.join(IMG, fname)
        if not os.path.exists(path):
            continue
        doc.add_picture(path, width=Inches(4.8))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        c = doc.add_paragraph(cap)
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.runs[0].italic = True


for title, body in sections:
    doc.add_heading(title, level=1)
    doc.add_paragraph(body)

doc.add_heading("6. Exploratory data analysis", level=1)
doc.add_paragraph("The charts below summarise the main patterns in the data. Prices are right-skewed, differ a lot "
                  "between cities, and are strongly related to area and location score.")
add_figures(charts_eda)

doc.add_heading("7. Results", level=1)
doc.add_paragraph(results_text)
table = doc.add_table(rows=1, cols=5)
table.style = "Light Grid Accent 1"
for i, h in enumerate(["Model", "R2 (test)", "CV R2", "MAE", "RMSE"]):
    table.rows[0].cells[i].text = h
for r_ in m["results"]:
    cells = table.add_row().cells
    cells[0].text = r_["model"]
    cells[1].text = str(r_["r2"])
    cells[2].text = str(r_["cv_r2"])
    cells[3].text = f"{r_['mae']:,}"
    cells[4].text = f"{r_['rmse']:,}"
doc.add_paragraph()
add_figures(charts_model)

doc.add_heading("8. Web application", level=1)
doc.add_paragraph("The trained pipeline is loaded by a Flask app (backend/app.py). The /predict endpoint validates "
                  "the input, runs the model and returns the estimated price as JSON. The frontend is a single HTML "
                  "page with a form where the user picks a city, enters the property details and sees the price.")
doc.add_heading("9. Conclusion", level=1)
doc.add_paragraph(conclusion)
doc.add_heading("10. Future scope", level=1)
doc.add_paragraph(future)

out = args.out or os.path.join(BASE, "House_Price_Prediction_Report.docx")
doc.save(out)

# ---------- html ----------
rows_html = "".join(
    f"<tr><td>{r_['model']}</td><td>{r_['r2']}</td><td>{r_['cv_r2']}</td><td>{r_['mae']:,}</td><td>{r_['rmse']:,}</td></tr>"
    for r_ in m["results"]
)
secs_html = "".join(f"<h2>{t_}</h2><p>{b}</p>" for t_, b in sections)
figs = lambda items: "".join(
    f'<figure><img src="report_images/{f}" alt="{c}"><figcaption>{c}</figcaption></figure>' for f, c in items)
html = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>House Price Prediction Report</title>
<style>body{{font-family:Segoe UI,Arial,sans-serif;max-width:820px;margin:30px auto;padding:0 16px;color:#1f2937;line-height:1.6}}
h1{{color:#1e3a8a}}img{{max-width:100%}}figure{{text-align:center;margin:18px 0}}figcaption{{font-size:13px;color:#6b7280}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #d1d5db;padding:6px 10px;text-align:left}}th{{background:#eff6ff}}</style></head>
<body><h1>House Price Prediction using Data Analytics with AI</h1><p>Submitted by {args.name} | {args.college}</p>
{secs_html}<h2>6. Exploratory data analysis</h2>{figs(charts_eda)}
<h2>7. Results</h2><p>{results_text}</p>
<table><tr><th>Model</th><th>R2 (test)</th><th>CV R2</th><th>MAE</th><th>RMSE</th></tr>{rows_html}</table>{figs(charts_model)}
<h2>9. Conclusion</h2><p>{conclusion}</p><h2>10. Future scope</h2><p>{future}</p></body></html>"""
with open(os.path.join(BASE, "house-price-prediction-project-report.html"), "w", encoding="utf-8") as f:
    f.write(html)

print("report saved:", out)
